# key → category dict
_BY_KEY = {c['key']: c for c in CATEGORIES}

_GROUP_PREFIX_NOTE = '（群組指令加 / 開頭，私聊免前綴）'
_AI_NOTE = '💡 標（AI）的是例句：用自然講法即可，同義說法 AI 都懂'


def _format_entries(entries) -> str:
    return '\n'.join(f'・{cmd}\n　{desc}' for cmd, desc in entries)


def render_overview() -> str:
    """總覽短文：每分類標題＋代表指令，配 Quick Reply 分類按鈕用"""
    lines = [
        '🤖 派班小幫手 指令總覽',
        '💡 直接用問的最快，例如：',
        '「改已完成班次的金額怎麼做？」',
        '「司機接近怎麼通知接送人員？」',
        _GROUP_PREFIX_NOTE, '',
    ]
    for c in CATEGORIES:
        lines.append(f"{c['emoji']} {c['title']}：{'、'.join(c['brief'])}")
    lines += [
        '',
        '📖 按下方按鈕看各分類完整清單',
        '也可直接打「幫助 查詢」…「幫助 全部」',
    ]
    return '\n'.join(lines)


def render_category(key: str) -> str:
    """單一分類完整清單（冷門指令全列）"""
    c = _BY_KEY[key]
    parts = [
        f"{c['emoji']} {c['title']}｜完整指令清單",
        _GROUP_PREFIX_NOTE,
        '',
        _format_entries(c['entries']),
    ]
    if any('（AI）' in cmd for cmd, _ in c['entries']):
        parts += ['', _AI_NOTE]
    return '\n'.join(parts)


def render_full() -> str:
    """全分類長文字（可長按轉傳保存）"""
    parts = [
        '🤖 派班小幫手 完整指令清單',
        _GROUP_PREFIX_NOTE,
        _AI_NOTE,
    ]
    for c in CATEGORIES:
        parts += [
            '',
            f"━━ {c['emoji']} {c['title']} ━━",
            _format_entries(c['entries']),
        ]
    return '\n'.join(parts)


def _quick_reply_items() -> list:
    items = [
        {
            'type': 'action',
            'action': {
                'type': 'message',
                'label': f"{c['emoji']} {c['btn']}",
                'text': f"幫助 {c['btn']}",
            },
        }
        for c in CATEGORIES
    ]
    items.append({
        'type': 'action',
        'action': {'type': 'message', 'label': '📖 全部', 'text': '幫助 全部'},
    })
    return items


def overview_message() -> dict:
    """總覽 message dict（純文字 + 分類 Quick Reply 按鈕）"""
    return {
        'type': 'quick_reply',
        'text': render_overview(),
        'quick_reply': {'items': _quick_reply_items()},
    }


def resolve_category(arg: str) -> Optional[str]:
    """把「幫助 X」的 X 解析成分類 key；'full' = 全清單；不認得回 None"""
    a = (arg or '').strip()
    if not a:
        return None
    if a in {'全部', '完整', 'all', 'All', 'ALL'}:
        return 'full'
    for c in CATEGORIES:
        if a == c['title'] or a in c['aliases']:
            return c['key']
    return None


def try_handle_help(text: str) -> Optional[dict]:
    """幫助指令 dispatch：回 LINE message dict；不是幫助指令回 None

    - 幫助 / help / 指令 / 說明        → 總覽 + 分類按鈕
    - 幫助 查詢（等分類名 / 別名）      → 該分類完整清單
    - 幫助 全部                        → 全清單長文字
    - 幫助 <不認得的字> → None（留給 AI 處理，不劫持「幫助我查X」這類請求）
    """
    s = (text or '').strip()
    if not s:
        return None
    if s in HELP_TRIGGERS:
        return overview_message()
    if s.startswith('幫助'):
        key = resolve_category(s[len('幫助'):])
        if key == 'full':
            return {'type': 'text', 'text': render_full()}
        if key:
            return {'type': 'text', 'text': render_category(key)}
    return None


